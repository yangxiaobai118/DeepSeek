/**
 * Generate a self-contained nginx.conf.
 *
 * Two modes:
 *  - "http":   nginx owns 80 and 443. Panels/web live on 443 via server_name.
 *              Proxy inbounds must listen on their own (non-443) ports.
 *  - "stream": nginx's stream module owns 443 and routes by SNI (ssl_preread).
 *              nginx's http servers move to 127.0.0.1:<nginxInternalTls>.
 *              Proxy inbounds bind loopback and are reached through the map.
 */
export function generateNginx(c) {
  const { ports, nginx, panels, server } = c;
  const mode = nginx.mode;
  const cert = server.cert || {};
  const hasCert = Boolean(cert.certFile && cert.keyFile);
  const tlsListen =
    mode === 'stream' ? '127.0.0.1:' + ports.nginxInternalTls : String(ports.https);
  const http2Style = nginx.http2 || 'listen';

  const out = [];
  const w = (s = '') => out.push(s);

  const tlsLines = () => {
    if (!hasCert) return [];
    return [
      '        ssl_certificate     ' + cert.certFile + ';',
      '        ssl_certificate_key ' + cert.keyFile + ';',
      '        ssl_protocols TLSv1.2 TLSv1.3;',
      '        ssl_session_cache shared:SSL:10m;',
      '        ssl_session_timeout 1h;',
    ];
  };

  const securityHeaders = (indent = '        ') => [
    indent + 'add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;',
    indent + 'add_header X-Content-Type-Options "nosniff" always;',
    indent + 'add_header Referrer-Policy "no-referrer" always;',
  ];

  const listenLines = () => {
    if (http2Style === 'listen') return ['        listen ' + tlsListen + ' ssl http2;'];
    if (http2Style === 'directive') return ['        listen ' + tlsListen + ' ssl;', '        http2 on;'];
    return ['        listen ' + tlsListen + ' ssl;'];
  };

  w('# ============================================================');
  w('#  generated by uniproxy - do not edit by hand.');
  w('#  regenerate: node src/index.js generate -c config.json -o out');
  w('#  nginx mode: ' + mode);
  w('# ============================================================');
  w('');
  w('worker_processes auto;');
  w('error_log /var/log/nginx/error.log warn;');
  w('pid /run/nginx.pid;');
  w('');
  w('events { worker_connections 1024; }');
  w('');
  w('http {');
  w('    types {');
  w('        text/html                     html htm shtml;');
  w('        text/css                      css;');
  w('        text/xml                      xml;');
  w('        application/javascript        js;');
  w('        application/json              json;');
  w('        image/gif                     gif;');
  w('        image/jpeg                    jpeg jpg;');
  w('        image/png                     png;');
  w('        image/svg+xml                 svg svgz;');
  w('        image/webp                    webp;');
  w('        image/x-icon                  ico;');
  w('        font/woff                     woff;');
  w('        font/woff2                    woff2;');
  w('        application/pdf               pdf;');
  w('        application/zip               zip;');
  w('        video/mp4                     mp4;');
  w('        text/plain                    txt;');
  w('        application/octet-stream      bin exe dll;');
  w('    }');
  w('    default_type  application/octet-stream;');
  w('    sendfile      on;');
  w('    keepalive_timeout 65;');
  w('    server_tokens off;');
  w('');
  w('    # websocket upgrade: only send "upgrade" when the client asked for it');
  w('    map $http_upgrade $connection_upgrade {');
  w('        default upgrade;');
  w("        ''      close;");
  w('    }');
  w('');
  w('    gzip on;');
  w('    gzip_min_length 1024;');
  w('    gzip_types text/plain text/css application/json application/javascript application/xml image/svg+xml;');
  w('');
  w('    # ---- plain HTTP: redirect everything to TLS ----');
  w('    server {');
  w('        listen ' + ports.http + ';');
  w('        server_name _;');
  w('        return 301 https://$host$request_uri;');
  w('    }');
  w('');

  const panelList = [
    { key: 'xui', p: panels.xui },
    { key: 'sui', p: panels.sui },
  ];

  if (mode === 'http') {
    // In http mode nginx terminates TLS itself, so ACME HTTP-01 can also work
    // on port 80 for the certificate in server.cert.
  }

  if (c.ui && c.ui.domain) {
    const uiPort = (c.ui && c.ui.port) || 8788;
    w('    # ---- u-ui panel: ' + c.ui.domain + ' -> 127.0.0.1:' + uiPort + ' ----');
    w('    server {');
    for (const line of listenLines()) w(line);
    w('        server_name ' + c.ui.domain + ';');
    for (const line of tlsLines()) w(line);
    for (const line of securityHeaders()) w(line);
    w('        location / {');
    w('            proxy_pass http://127.0.0.1:' + uiPort + ';');
    w('            proxy_http_version 1.1;');
    w('            proxy_set_header Host $host;');
    w('            proxy_set_header X-Real-IP $remote_addr;');
    w('            proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;');
    w('            proxy_set_header X-Forwarded-Proto $scheme;');
    w('            proxy_set_header Upgrade $http_upgrade;');
    w('            proxy_set_header Connection $connection_upgrade;');
    w('            proxy_read_timeout 3600s;');
    w('            proxy_buffering off;');
    w('        }');
    w('    }');
    w('');
  }

  for (const site of nginx.sites || []) {
    w('    # ---- website: ' + site.serverName + ' ----');
    w('    server {');
    for (const line of listenLines()) w(line);
    w('        server_name ' + site.serverName + ';');
    for (const line of tlsLines()) w(line);
    for (const line of securityHeaders()) w(line);
    w('        root  ' + (site.root || '/var/www/html') + ';');
    w('        index ' + (site.index || 'index.html') + ';');
    w('        location / { try_files $uri $uri/ =404; }');
    w('    }');
    w('');
  }

  for (const { key, p } of panelList) {
    if (!p || !p.enabled || !p.domain) continue;
    w('    # ---- panel: ' + key + ' -> ' + (p.listen || '127.0.0.1') + ':' + p.port + ' ----');
    w('    server {');
    for (const line of listenLines()) w(line);
    w('        server_name ' + p.domain + ';');
    for (const line of tlsLines()) w(line);
    for (const line of securityHeaders()) w(line);
    w('        location / {');
    w('            proxy_pass http://' + (p.listen || '127.0.0.1') + ':' + p.port + ';');
    w('            proxy_http_version 1.1;');
    w('            proxy_set_header Host $host;');
    w('            proxy_set_header X-Real-IP $remote_addr;');
    w('            proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;');
    w('            proxy_set_header X-Forwarded-Proto $scheme;');
    w('            proxy_set_header X-Forwarded-Host $host;');
    w('            proxy_set_header Upgrade $http_upgrade;');
    w('            proxy_set_header Connection $connection_upgrade;');
    w('            proxy_read_timeout 86400s;');
    w('            proxy_buffering off;');
    w('        }');
    w('    }');
    w('');
  }

  // Subscription server of the s-ui panel (default 2096 + /sub/), reached on
  // its own hostname so links stay short and nginx keeps one TLS certificate.
  for (const { key, p } of panelList) {
    if (!p || !p.enabled || !p.sub || !p.sub.enabled) continue;
    const subHost = p.sub.domain || p.domain;
    if (!subHost) continue;
    w('    # ---- ' + key + ' subscriptions -> ' + (p.listen || '127.0.0.1') + ':' + p.sub.port + ' ----');
    w('    server {');
    for (const line of listenLines()) w(line);
    w('        server_name ' + subHost + ';');
    for (const line of tlsLines()) w(line);
    for (const line of securityHeaders()) w(line);
    w('        location ' + p.sub.path + ' {');
    w('            proxy_pass http://' + (p.listen || '127.0.0.1') + ':' + p.sub.port + ';');
    w('            proxy_set_header Host $host;');
    w('            proxy_set_header X-Real-IP $remote_addr;');
    w('            proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;');
    w('            proxy_set_header X-Forwarded-Proto $scheme;');
    w('            proxy_buffering off;');
    for (const line of securityHeaders('            ')) w(line);
    w('            add_header Cache-Control "no-store" always;');
    w('        }');
    w('    }');
    w('');
  }

  for (const site of nginx.extraSites || []) {
    if (!site.serverName || !site.upstream) continue;
    w('    # ---- extra site: ' + site.serverName + ' -> ' + site.upstream + ' ----');
    w('    server {');
    for (const line of listenLines()) w(line);
    w('        server_name ' + site.serverName + ';');
    for (const line of tlsLines()) w(line);
    for (const line of securityHeaders()) w(line);
    w('        location / {');
    w('            proxy_pass http://' + site.upstream + ';');
    w('            proxy_set_header Host $host;');
    w('            proxy_set_header X-Real-IP $remote_addr;');
    w('            proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;');
    w('            proxy_set_header Upgrade $http_upgrade;');
    w('            proxy_set_header Connection $connection_upgrade;');
    w('        }');
    w('    }');
    w('');
  }

  w('}');
  w('');

  if (mode === 'stream') {
    const routes = new Map();
    if (c.ui && c.ui.domain) routes.set(c.ui.domain, '127.0.0.1:' + ports.nginxInternalTls);
    for (const site of nginx.sites || []) {
      routes.set(site.serverName, '127.0.0.1:' + ports.nginxInternalTls);
    }
    for (const { p } of panelList) {
      if (p && p.enabled && p.domain) {
        routes.set(p.domain, '127.0.0.1:' + ports.nginxInternalTls);
      }
      if (p && p.enabled && p.sub && p.sub.enabled) {
        const subHost = p.sub.domain || p.domain;
        if (subHost) routes.set(subHost, '127.0.0.1:' + ports.nginxInternalTls);
      }
    }
    for (const site of nginx.extraSites || []) {
      if (site.serverName) routes.set(site.serverName, '127.0.0.1:' + ports.nginxInternalTls);
    }
    const inbounds = [
      ...(c.xray.inbounds || []),
      ...(c.singbox.inbounds || []),
    ];
    for (const ib of inbounds) {
      if (!ib.sni || !ib.port) continue;
      const host = ib.listen && ib.listen !== '0.0.0.0' ? ib.listen : '127.0.0.1';
      routes.set(ib.sni, host + ':' + ib.port);
    }

    w('stream {');
    w('    # SNI-based 443 multiplexer: one socket, many backends');
    w('    map $ssl_preread_server_name $uniproxy_backend {');
    for (const [sni, backend] of routes) {
      w('        ' + sni + '  ' + backend + ';');
    }
    w('        default  127.0.0.1:' + ports.nginxInternalTls + ';');
    w('    }');
    w('');
    w('    server {');
    w('        listen ' + ports.https + ';');
    w('        proxy_pass $uniproxy_backend;');
    w('        ssl_preread on;');
    w('        proxy_connect_timeout 10s;');
    w('        proxy_timeout 3600s;');
    w('    }');
    w('}');
    w('');
  }

  return out.join('\n');
}