import { x25519PublicFromPrivate } from '../util.js';

/**
 * Clash / Mihomo profile generator (zero dependencies).
 *
 * Only transports Clash understands are emitted: tcp, ws, grpc, h2 and
 * httpupgrade. xhttp records are skipped with a comment instead of producing a
 * profile the client silently rejects.
 */
const CLASH_TRANSPORTS = new Set(['tcp', 'ws', 'grpc', 'h2', 'httpupgrade']);

export function generateClash(c, records) {
  const proxies = [];
  const skipped = [];
  for (const record of records) {
    const proxy = clashProxy(record, proxies);
    if (proxy) proxies.push(proxy);
    else skipped.push(record.remark + ' (' + (record.inbound.network || 'tcp') + ')');
  }

  const doc = {
    port: 7890,
    'socks-port': 7891,
    'mixed-port': 7890,
    'allow-lan': false,
    mode: 'rule',
    'log-level': 'info',
    'external-controller': '127.0.0.1:9090',
  };

  const lines = [
    '# generated by uniproxy - Clash / Mihomo profile',
    '# import this file into your client, or fetch the subscription URL',
    '',
    ...emit(doc, 0),
    '',
    'proxies:',
  ];

  if (!proxies.length) lines.push('  []');
  else for (const p of proxies) lines.push(...emitListItem(p, 1));

  if (skipped.length) {
    lines.push('', '# skipped (Clash has no client for this transport):');
    for (const s of skipped) lines.push('#   - ' + s);
  }

  if (proxies.length) {
    lines.push(
      '',
      'proxy-groups:',
      '  - name: PROXY',
      '    type: select',
      '    proxies:',
      ...proxies.map((p) => '      - ' + yamlScalar(p.name)),
      '',
      'rules:',
      '  - MATCH,PROXY',
      '',
    );
  }

  return lines.join('\n');
}

function clashProxy(record, existing) {
  const ib = record.inbound;
  const network = ib.network || 'tcp';
  if (!CLASH_TRANSPORTS.has(network)) return null;

  const base = {
    name: uniqueName(record.remark, existing),
    type: record.protocol,
    server: record.server,
    port: Number(record.port),
    udp: true,
  };

  if (record.protocol === 'trojan') {
    base.password = record.clientId || 'REPLACE_PASSWORD';
  } else {
    base.uuid = record.clientId || 'REPLACE_UUID';
    if (record.protocol === 'vmess') {
      base.alterId = 0;
      base.cipher = 'auto';
    }
  }

  const tls = ib.security === 'tls' || ib.security === 'reality';
  if (tls) {
    base.tls = true;
    base['skip-cert-verify'] = false;
    if (ib.sni) base.servername = ib.sni;
    if (ib.security === 'reality') {
      base['client-fingerprint'] = ib.fingerprint || 'chrome';
      const opts = { 'public-key': realityPublicKey(ib) };
      const sid = (ib.reality && ib.reality.shortIds && ib.reality.shortIds[0]) || '';
      if (sid) opts['short-id'] = sid;
      base['reality-opts'] = opts;
      if (record.flow) base.flow = record.flow;
    } else if (ib.fingerprint) {
      base['client-fingerprint'] = ib.fingerprint;
    }
  }

  if (network !== 'tcp') base.network = network;
  const host = ib.host || ib.wsHost || ib.httpHost;
  const path = ib.path || ib.wsPath || ib.h2Path || (network === 'ws' ? '/ws' : '/');

  if (network === 'ws') {
    const opts = { path };
    if (host) opts.headers = { Host: host };
    base['ws-opts'] = opts;
  } else if (network === 'grpc') {
    base['grpc-opts'] = { 'grpc-service-name': ib.grpcService || 'grpc' };
  } else if (network === 'h2') {
    const opts = { path };
    if (host) opts.host = [host];
    base['h2-opts'] = opts;
  } else if (network === 'httpupgrade') {
    const opts = { path };
    if (host) opts.headers = { Host: host };
    base['httpupgrade-opts'] = opts;
  }

  return base;
}

function realityPublicKey(ib) {
  if (ib.reality && ib.reality.publicKey) return ib.reality.publicKey;
  try {
    return x25519PublicFromPrivate(ib.reality.privateKey);
  } catch {
    return 'REPLACE_PUBLIC_KEY';
  }
}

function uniqueName(name, existing) {
  let candidate = name;
  let n = 2;
  while (existing.some((p) => p.name === candidate)) candidate = name + '-' + n++;
  return candidate;
}

/** YAML scalar with quoting only where needed. */
export function yamlScalar(value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  const s = String(value);
  const plain = /^[A-Za-z0-9_][A-Za-z0-9_./:@+ =-]*$/.test(s);
  const reserved = /^(true|false|null|yes|no|on|off|~)$/i.test(s);
  if (plain && !reserved && !/[:#]\s/.test(s) && !s.endsWith(' ')) return s;
  return JSON.stringify(s);
}

function emit(obj, indent) {
  const pad = '  '.repeat(indent);
  const lines = [];
  for (const [key, value] of Object.entries(obj)) {
    if (value === undefined) continue;
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      lines.push(pad + key + ':');
      lines.push(...emit(value, indent + 1));
    } else if (Array.isArray(value)) {
      if (!value.length) lines.push(pad + key + ': []');
      else {
        lines.push(pad + key + ':');
        for (const item of value) lines.push(pad + '  - ' + yamlScalar(item));
      }
    } else {
      lines.push(pad + key + ': ' + yamlScalar(value));
    }
  }
  return lines;
}

function emitListItem(obj, indent) {
  const pad = '  '.repeat(indent);
  const entries = Object.entries(obj).filter(([, v]) => v !== undefined);
  const lines = [];
  entries.forEach(([key, value], index) => {
    const prefix = index === 0 ? pad + '- ' : pad + '  ';
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      lines.push(prefix + key + ':');
      lines.push(...emit(value, indent + 2));
    } else if (Array.isArray(value)) {
      lines.push(prefix + key + ':');
      for (const item of value) lines.push(pad + '    - ' + yamlScalar(item));
    } else {
      lines.push(prefix + key + ': ' + yamlScalar(value));
    }
  });
  return lines;
}
